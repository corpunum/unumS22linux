"""s22_voice: natural-voice helpers for the S22 voice loop (pure Python, no I/O at import).

A faithful port of the pieces OpenUnum 89ac48de added for natural-sounding
speech, so the phone's push-to-talk assistant and s22-converse get them without
a Node round trip or a risky OpenUnum update on the phone:

  enhance_for_voice()   src/core/spoken-form.mjs   markdown stripped, lists ->
                        "First... Then... And finally...", pauses, chatty
                        EN/EL fillers (seeded, so the output is reproducible)
  classify_question()   src/ui/modules/voice-fillers.js   question -> category
  pick_clip_index()     same file                  never the same clip twice
  ThinkingSpeaker       src/ui/modules/voice-thinking.js  short spoken thinking

Parity with the JavaScript originals is checked by test_s22_voice.py against
fixtures generated by running the rig's modules under node (voice/parity.json).
Installed next to s22-assistant as /srv/s22/hardware/bin/s22_voice.py.
"""
from __future__ import annotations

import json
import math
import os
import re
import unicodedata
from pathlib import Path

GREEK_RE = re.compile('[Ͱ-Ͽἀ-῿]')
_LETTER = r'[^\W\d_]'          # \p{L}


def detect_script(text: str = '') -> str:
    s = str(text)
    greek = len(re.findall('[Ͱ-Ͽἀ-῿]', s))
    latin = len(re.findall('[A-Za-z]', s))
    if greek == 0 and latin == 0:
        return 'unknown'
    return 'greek' if greek > latin * 0.25 else 'latin'


# ---------------------------------------------------------------- stage 1: strip

def strip_for_speech(text: str = '') -> str:
    s = str(text or '')
    greek = bool(GREEK_RE.search(s))
    code = ' (κώδικας) ' if greek else ' (code) '
    s = re.sub(r'```[\s\S]*?```', code, s)
    s = re.sub(r'~~~[\s\S]*?~~~', code, s)
    s = re.sub(r'^\s*\|.*\|\s*$', '', s, flags=re.M)
    s = re.sub(r'^\s*[-:| ]{4,}\s*$', '', s, flags=re.M)
    s = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', s)
    s = re.sub(r'https?://[^\s)\]]+', ' ένας σύνδεσμος ' if greek else ' a link ', s)
    s = re.sub(r'`([^`]*)`', r'\1', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'\1', s)
    s = re.sub(r'(^|\s)\*([^*\n]+)\*', r'\1\2', s)
    s = re.sub(r'(^|\s)_([^_\n]+)_', r'\1\2', s)
    s = re.sub(r'^\s{0,3}#{1,6}\s*', '', s, flags=re.M)
    s = re.sub(r'^\s{0,3}>\s?', '', s, flags=re.M)
    s = re.sub(r'(?:/[A-Za-z0-9_.-]+){2,}',
               lambda m: ' ' + ([p for p in m.group(0).split('/') if p] or [m.group(0)])[-1] + ' ', s)
    s = re.sub(r'^\s*[-*+]\s+', '', s, flags=re.M)
    s = re.sub(r'^\s*\d+[.)]\s+', '', s, flags=re.M)
    s = re.sub('[─-╿▀-▟]', ' ', s)
    s = re.sub('[\U0001F300-\U0001FAFF☀-➿️]', ' ', s)
    s = s.replace('\r', '')
    s = re.sub(r'\n{2,}', '. ', s)
    s = s.replace('\n', '. ')
    s = re.sub(r'\.\s*\.', '.', s)
    s = re.sub(r'\s{2,}', ' ', s).strip()
    s = re.sub(r'^[.\s]+', '', s)
    return s


# ---------------------------------------------------------------- stage 2: enhance

SEQUENCE_WORDS = {
    'en': {'first': 'First,', 'middle': ['Then,', 'Next,', 'After that,'], 'last': 'And finally,'},
    'el': {'first': 'Πρώτα,', 'middle': ['Μετά,', 'Έπειτα,', 'Στη συνέχεια,'], 'last': 'Και τέλος,'},
}
HEADING_LEAD = {'en': 'Now, about', 'el': 'Τώρα, για'}
FILLER_BANK = {
    'en': ['Well…', 'Hmm…', 'So…', 'Okay…', 'Right…', "Let's see…", 'Alright…', 'Now…', 'You know…', 'Um…'],
    'el': ['Εμμ…', 'Λοιπόν…', 'Για να δω…', 'Να δούμε…', 'Ωραία…', 'Χμμ…', 'Εντάξει…', 'Άκου…', 'Να σκεφτώ…'],
}
LEAD_IN_RE = re.compile(r'^(?:First,|Then,|Next,|After that,|And finally,|Now, about|Πρώτα,|Μετά,|Έπειτα,|Στη συνέχεια,|Και τέλος,|Τώρα, για)')
FILLER_RATE = {'chatty': 2.5, 'light': 5}
LONG_SENTENCE = 140
CONJUNCTION_RE = re.compile(r'\s(?=(?:and|but|because|which|so|while|although|και|αλλά|επειδή|ενώ|που|όμως)\s)', re.I)
_BULLET = r'(?:[-*+•]|\d+[.)])'
_SPLIT_GAP = re.compile(r'(?<=[.!?;…])\s+')
_M32 = 0xFFFFFFFF


def _hash_seed(value) -> int:
    h = 2166136261
    for ch in str(value):
        h ^= ord(ch)
        h = (h * 16777619) & _M32
    return h


def _imul(a: int, b: int) -> int:
    return (a * b) & _M32


def seeded_random(seed):
    """mulberry32, bit-exact with the JS version; returns a callable giving floats in [0, 1)."""
    state = [_hash_seed(seed) or 1]

    def rand() -> float:
        a = (state[0] + 0x6D2B79F5) & _M32
        state[0] = a
        t = _imul(a ^ (a >> 15), 1 | a)
        t = ((t + _imul(t ^ (t >> 7), 61 | t)) & _M32) ^ t
        return ((t ^ (t >> 14)) & _M32) / 4294967296
    return rand


def _js_round(x: float) -> int:
    return math.floor(x + 0.5)


def _soft_lower(text: str) -> str:
    if len(text) >= 2 and text[0].isupper() and (text[1].islower() or text[1].isspace()) \
            and not re.match(r'^I\b', text):
        return text[0].lower() + text[1:]
    return text


def _spoken_structure(text: str, lang: str) -> str:
    words = SEQUENCE_WORDS[lang]
    lines = str(text).replace('\r', '').split('\n')
    out = []
    in_fence = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if re.match(r'^\s*(```|~~~)', line):
            in_fence = not in_fence
            out.append(line)
            i += 1
            continue
        if in_fence:
            out.append(line)
            i += 1
            continue
        heading = re.match(r'^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$', line)
        if heading:
            title = re.sub(r'[*_`:]+', '', heading.group(1))
            title = re.sub(r'[.!?:]+$', '', title).strip()
            if title:
                out.append(f'{HEADING_LEAD[lang]} {_soft_lower(title)}.')
            i += 1
            continue
        if re.match(rf'^\s*{_BULLET}\s+\S', line):
            items = []
            while i < len(lines) and re.match(rf'^\s*{_BULLET}\s+\S', lines[i]):
                items.append(re.sub(rf'^\s*{_BULLET}\s+', '', lines[i]).strip())
                i += 1
            for idx, item in enumerate(items):
                body = re.sub(r'[.;:,]+$', '', item)
                end = '' if re.search(r'[!?]$', body) else '.'
                if len(items) == 1:
                    out.append(body if end == '' else f'{body}.')
                    continue
                if idx == 0:
                    lead = words['first']
                elif idx == len(items) - 1:
                    lead = words['last']
                else:
                    lead = words['middle'][(idx - 1) % len(words['middle'])]
                out.append(f'{lead} {_soft_lower(body)}{end}')
            continue
        out.append(re.sub(r':\s*$', '.', line))
        i += 1
    return '\n'.join(out)


def _spoken_symbols(text: str, lang: str) -> str:
    el = lang == 'el'
    s = text
    s = re.sub(r'\s*\(([^()]{1,80})\)\s*', lambda m: f', {m.group(1).strip()}, ', s)
    s = re.sub(r'\s*[→⇒➜]\s*', ' σε ' if el else ' to ', s)
    s = re.sub(r'\s*&\s*', ' και ' if el else ' and ', s)
    s = re.sub(r'(\d)\s*%', r'\1 τοις εκατό' if el else r'\1 percent', s)
    s = re.sub(r'[~≈]\s*(?=\d)', 'περίπου ' if el else 'about ', s)
    s = re.sub(r'\s=\s', ' ισούται με ' if el else ' equals ', s)
    s = re.sub(r'#(?=\d)', 'αριθμός ' if el else 'number ', s)
    s = re.sub(rf'({_LETTER}{{2,}})/({_LETTER}{{2,}})', r'\1 ή \2' if el else r'\1 or \2', s)
    s = re.sub(r'\s/\s', ', ', s)
    s = re.sub(r'\s*\|\s*', ', ', s)
    s = re.sub(r'\s*[—–]\s*', ', ', s)
    s = re.sub(r'[*_^<>{}\[\]\\@]+', ' ', s)
    s = re.sub(r'\s+,', ',', s)
    s = re.sub(r',(\s*,)+', ',', s)
    s = re.sub(r',\s*([.!?;…])', r'\1', s)
    s = re.sub(r'^[,\s]+', '', s)
    s = re.sub(r'\s{2,}', ' ', s)
    return s.strip()


def _pause_long_sentence(sentence: str) -> str:
    if len(sentence) <= LONG_SENTENCE or re.search(r'[,…;:].{40,}[,…;:]', sentence):
        return sentence
    mid = len(sentence) / 2
    best = -1
    for m in CONJUNCTION_RE.finditer(sentence):
        if m.start() < 40 or m.start() > len(sentence) - 30:
            continue
        if best < 0 or abs(m.start() - mid) < abs(best - mid):
            best = m.start()
    if best >= 0:
        return sentence if sentence[:best].endswith(',') else sentence[:best] + ',' + sentence[best:]
    gap = sentence.find(' ', math.floor(mid))
    if gap < 40 or gap > len(sentence) - 20:
        return sentence
    return sentence[:gap] + '…' + sentence[gap:]


def _split_sentences(s: str) -> list:
    """Split after . ! ? ; … when the next word starts upper-case, a digit, a quote or '('."""
    parts, last = [], 0
    for m in _SPLIT_GAP.finditer(s):
        nxt = s[m.end():m.end() + 1]
        if nxt and (nxt.isupper() or nxt.isnumeric() or nxt in '"«“\'('):
            parts.append(s[last:m.start()])
            last = m.end()
    parts.append(s[last:])
    return parts


def enhance_for_voice(text: str = '', lang=None, style: str = 'chatty', seed=None) -> str:
    raw = ''
    try:
        raw = str(text or '')
        if style in ('off', False):
            return strip_for_speech(raw)
        if lang in ('el', 'greek'):
            language = 'el'
        elif lang in ('en', 'latin'):
            language = 'en'
        else:
            language = 'el' if detect_script(raw) == 'greek' else 'en'
        s = strip_for_speech(_spoken_structure(raw, language))
        s = _spoken_symbols(s, language)
        if not s:
            return ''
        sentences = [x for x in (_pause_long_sentence(p.strip()) for p in _split_sentences(s)) if x]
        rate = FILLER_RATE.get(style, FILLER_RATE['chatty'])
        if len(sentences) < 2:
            return ' '.join(sentences)
        rand = seeded_random(s if seed is None else seed)
        bank = FILLER_BANK[language]
        max_fillers = math.ceil(len(sentences) / rate)
        out = []
        used = 0
        last_filler_at = -10
        next_at = math.floor(rand() * 2)
        last_pick = -1
        for idx, sentence in enumerate(sentences):
            blocked = (LEAD_IN_RE.search(sentence) or re.search('["«»“”]', sentence)
                       or re.match(r'^\d', sentence) or len(sentence) < 15 or idx - last_filler_at < 2)
            if idx >= next_at and used < max_fillers and not blocked:
                pick = math.floor(rand() * len(bank))
                if pick == last_pick:
                    pick = (pick + 1) % len(bank)
                last_pick = pick
                out.append(bank[pick])
                used += 1
                last_filler_at = idx
                next_at = idx + _js_round(rate - 0.5 + rand())
            out.append(sentence)
        return ' '.join(out)
    except Exception:
        try:
            return strip_for_speech(raw)
        except Exception:
            return raw


_FRAMEWORK_NOTE = re.compile(r'^(verification (warning|note)|evidence (warning|note))\s*:', re.I)
_UNITS = [(re.compile(r'\s*°\s*C\b'), ' degrees Celsius'), (re.compile(r'\s*°\s*F\b'), ' degrees Fahrenheit'),
          (re.compile(r'\s*°'), ' degrees')]


def reply_to_speech(reply: str, style: str = 'chatty') -> str:
    """An OpenUnum reply -> text for the TTS: framework notes dropped, then enhance_for_voice.

    OpenUnum appends notes such as "Verification warning: ..." for the chat UI;
    they are not part of the answer. Unit symbols the JS port does not say
    ("°C") are spoken out here.
    """
    lines = [l for l in str(reply or '').splitlines() if not _FRAMEWORK_NOTE.match(l.strip())]
    text = '\n'.join(lines)
    for rx, sub in _UNITS:
        text = rx.sub(sub, text)
    return enhance_for_voice(text, style=style)


# ---------------------------------------------------------------- fillers

FILLER_CATEGORIES = ('general', 'search', 'analysis', 'creative', 'device', 'greeting')


def filler_lang(text: str = '') -> str:
    return 'el' if GREEK_RE.search(str(text)) else 'en'


def _fold(text: str) -> str:
    s = unicodedata.normalize('NFD', str(text or '').lower())
    s = re.sub('[̀-ͯ]', '', s)
    return s.replace('ς', 'σ')


def _word(alternatives: str):
    # The JS patterns are matched against folded text (final sigma -> sigma) but
    # written with final sigmas ("καιρος", "πες μου για"), so those alternatives
    # never match there. Fold the patterns too: deliberate fix, not parity.
    return re.compile(rf'(?:^|[\W\d_])(?:{alternatives.replace("ς", "σ")})', re.I)


_PATTERNS = [
    ('greeting', re.compile(r'^\s*(?:hi|hello|hey|yo|good (?:morning|evening|afternoon|night)|thanks|thank you|γεια|γειά σου|καλημερα|καλησπερα|καλως|ευχαριστω|χαιρετ)[\s!.,?]*(?:unum|there|σου|σας|παιδια)?[\s!.,?]*$', re.I)),
    ('device', _word(rf'(?:text|sms|message)\s+{_LETTER}+|call\b|dial\b|phone\b|my phone|battery|flashlight|screenshot|notification|volume|wifi|bluetooth|camera|alarm|timer|files? on|download folder|στειλε|μηνυμα σε|καλεσε|τηλεφων|μπαταρια|φακο|ειδοποιηση|ξυπνητηρι|χρονομετρ|αρχει[οα] στο|κινητο')),
    ('creative', _word(r'write|compose|draft|rewrite|translate|brainstorm|come up with|poem|story|essay|slogan|caption|email to|tagline|γραψε|συνθεσε|ξαναγραψε|μεταφρασε|ιστορια|ποιημα|σλογκαν|ιδεες|εμαιλ')),
    ('analysis', _word(r'calculate|compute|how much|how many|compare|analy[sz]e|estimate|percent|average|sum of|total|solve|which is (?:better|bigger|faster)|why does|υπολογισε|ποσο|ποσα|συγκριν|αναλυσ|εκτιμησ|ποσοστο|μεσο|αθροισμα|λυσε|γιατι|\d\s*%|\d\s*[-+*/x×÷]\s*\d')),
    ('search', _word(r'search|look up|lookup|find|google|what is|what are|who is|who was|when did|where is|latest|news|weather|price of|define|tell me about|ψαξε|βρες|αναζητ|τι ειναι|ποιος ειναι|ποιος ηταν|ποτε|που ειναι|νεα|καιρος|τιμη|πες μου για|τι εγινε')),
]


def classify_question(text: str = '') -> str:
    s = _fold(text).strip()
    if not s:
        return 'general'
    for category, rx in _PATTERNS:
        if rx.search(s):
            return category
    return 'general'


def pick_clip_index(count, last_index: int = -1, rand=None) -> int:
    import random
    rand = rand or random.random
    n = max(0, int(count or 0))
    if n == 0:
        return -1
    if n == 1:
        return 0
    pick = min(n - 1, math.floor(rand() * n))
    if pick == last_index:
        pick = (pick + 1) % n
    return pick


class FillerBank:
    """The rendered clips (manifest.json + <lang>/<category>/<n>.wav) and the no-repeat memory."""

    def __init__(self, root, chroot_prefix='', state_file=None, rand=None):
        self.root = Path(root)                       # host path of voice-fillers/
        self.chroot_prefix = str(chroot_prefix)      # host path of the chroot (to build in-chroot paths)
        self.state_file = Path(state_file) if state_file else None
        self.rand = rand
        try:
            self.manifest = json.loads((self.root / 'manifest.json').read_text())
        except (OSError, ValueError):
            self.manifest = {'clips': {}}

    def _last(self) -> dict:
        try:
            return json.loads(self.state_file.read_text()) if self.state_file else {}
        except (OSError, ValueError):
            return {}

    def pick(self, question: str, second: bool = False, lang: str | None = None):
        """(wav_path_in_chroot, info) or (None, info). Never the previous clip of the same lang/category.

        second=True (a "still thinking" clip) uses the general category, which
        also never repeats the clip just played. lang ('el'/'en', e.g. what the
        rig ASR heard) overrides the guess from the question's script.
        """
        lang = lang if lang in ('el', 'en') else filler_lang(question)
        category = 'general' if second else classify_question(question)
        clips = (self.manifest.get('clips', {}).get(lang, {}) or {}).get(category) or []
        clips = [c for c in clips if (self.root / lang / category / f"{c['n']}.wav").is_file()]
        info = {'lang': lang, 'category': category}
        if not clips:
            return None, info
        last = self._last()
        key = f'{lang}/{category}'
        last_n = last.get(key, -1)
        last_idx = next((i for i, c in enumerate(clips) if c['n'] == last_n), -1)
        clip = clips[pick_clip_index(len(clips), last_idx, self.rand)]
        last[key] = clip['n']
        last['_any'] = f"{key}/{clip['n']}"
        if self.state_file:
            try:
                self.state_file.parent.mkdir(parents=True, exist_ok=True)
                self.state_file.write_text(json.dumps(last))
            except OSError:
                pass
        info.update(n=clip['n'], phrase=clip.get('phrase'), duration_s=clip.get('durationSec'))
        path = self.root / lang / category / f"{clip['n']}.wav"
        prefix = self.chroot_prefix
        s = str(path)
        return (s[len(prefix):] if prefix and s.startswith(prefix) else s), info


# ---------------------------------------------------------------- spoken thinking

_THINK_MAX = 120
_THINK_MIN = 14
_LEAD_INS = {
    'en': ['Hmm, let me think…', 'Okay, so…', 'Let me see…', 'Right…', 'One moment…'],
    'el': ['Χμμ, για να σκεφτώ…', 'Εντάξει, λοιπόν…', 'Για να δω…', 'Ωραία…', 'Μισό λεπτό…'],
}


def summarize_thinking(paragraph: str, max_chars: int = _THINK_MAX) -> str:
    s = str(paragraph or '')
    s = re.sub(r'```[\s\S]*?```', ' ', s)
    s = re.sub(r'`([^`]*)`', r'\1', s)
    s = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', s)
    s = re.sub(r'https?://\S+', ' ', s)
    s = re.sub(r'(?:/[A-Za-z0-9_.-]+){2,}', ' ', s)
    s = re.sub(r'[*_#>]+', ' ', s)
    s = re.sub(r'^\s*(?:[-+•]|\d+[.)])\s+', '', s, flags=re.M)
    s = re.sub(r'\s+', ' ', s).strip()
    if not s or re.search(r'[{}<>]|=>|\(\)', s):
        return ''
    first = re.match(r'^.+?[.!?;…](?=\s|$)', s)
    if first and len(first.group(0)) >= _THINK_MIN:
        s = first.group(0)
    if len(s) > max_chars:
        cut = s[:max_chars]
        space = cut.rfind(' ')
        s = re.sub(r'[\s,.;:]+$', '', cut[:space] if space > max_chars * 0.5 else cut) + '…'
    return s if len(s) >= _THINK_MIN else ''


def thinking_to_spoken(paragraph: str, index: int = 0) -> str:
    summary = summarize_thinking(paragraph)
    if not summary:
        return ''
    bank = _LEAD_INS['el' if GREEK_RE.search(summary) else 'en']
    if index % 2 == 1:
        return summary
    return f'{bank[(index // 2) % len(bank)]} {summary}'


class ThinkingSpeaker:
    """push(token) -> text to speak or None; at most one chunk per min_gap_s; silent once the answer starts."""

    def __init__(self, min_gap_s: float = 4.0, now=None):
        import time
        self.min_gap_s = min_gap_s
        self.now = now or time.monotonic
        self.reset()

    def reset(self):
        self.buffer = ''
        self.pending = ''
        self.last_spoken_at = -math.inf
        self.spoken = 0
        self.answering = False

    def answer_started(self):
        self.answering = True
        self.pending = ''
        self.buffer = ''

    def _take(self, paragraph):
        chunk = thinking_to_spoken(paragraph, self.spoken)
        if chunk:
            self.pending = chunk

    def release(self):
        if self.answering or not self.pending or self.now() - self.last_spoken_at < self.min_gap_s:
            return None
        out, self.pending = self.pending, ''
        self.last_spoken_at = self.now()
        self.spoken += 1
        return out

    def push(self, token):
        if self.answering:
            return None
        self.buffer += str(token or '')
        parts = re.split(r'\n{2,}', self.buffer)
        self.buffer = parts.pop()
        for part in parts:
            self._take(part)
        if not parts and len(self.buffer) > 60 and re.search(r'[.!?…](?:\s|$)', self.buffer):
            m = re.match(r'^.+?[.!?…](?=\s|$)', self.buffer)
            if m and len(m.group(0)) >= _THINK_MIN:
                self._take(m.group(0))
                self.buffer = self.buffer[len(m.group(0)):]
        return self.release()
